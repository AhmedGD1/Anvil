using Godot;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Anvil;

public static class AnvilSceneGenerator
{
    private const string Indent = "    ";

    private const string AnimationsClassName = "Animations";

    private const string NodeClassSuffix = "Names";

    private sealed record Block(
        string Namespace,
        string ClassName,
        bool IsStandalone,
        AnvilSceneRule Rule,
        AnvilSceneReader.SceneInfo Info,
        Type ScriptType);

    public static void GenerateAndSave(AnvilRuleSet rules, HashSet<string> takenNames)
    {
        List<AnvilSceneRule> validRules = AnvilValidator.ValidateSceneRules(rules);

        var scriptTypes = AnvilScriptResolver.BuildScriptTypeMap();
        var claimedScripts = new Dictionary<Type, string>();

        StringBuilder sb = new();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using Godot;");
        sb.AppendLine();

        foreach (AnvilSceneRule rule in validRules)
        {
            Block block = BuildBlock(rule, scriptTypes, claimedScripts, takenNames);
            if (block is not null)
                AppendBlock(sb, block);
        }

        AnvilFileIO.SaveGeneratedFile("AnvilSceneIds", sb.ToString());
    }

    private static Block BuildBlock(AnvilSceneRule rule, Dictionary<string, Type> scriptTypes, Dictionary<Type, string> claimedScripts, HashSet<string> takenNames)
    {
        string scenePath = rule.ResolvePath();

        AnvilSceneReader.SceneInfo info = AnvilSceneReader.Read(scenePath);
        if (info is null)
            return null;

        if (info.ScriptPath.Length == 0)
        {
            GD.Print($"Anvil: Scene '{scenePath}' has no C# script on its root node " +
                    $"(only the root's script is used), generating the standalone class '{rule.OutputName}'.");
        }
        else if (!scriptTypes.TryGetValue(info.ScriptPath, out Type scriptType))
        {
            GD.PushWarning($"Anvil: The script '{info.ScriptPath}' of scene '{scenePath}' isn't in the built assembly yet " +
                        $"(not built, or not a Godot class; {scriptTypes.Count} script classes were found in the assembly). " +
                        $"Generating the standalone class '{rule.OutputName}' instead; " +
                        "build and generate again to move the ids into the script's class.");
        }
        else if (claimedScripts.TryGetValue(scriptType, out string otherScene))
        {
            GD.PushWarning($"Anvil: Scene '{scenePath}' shares the script '{info.ScriptPath}' with '{otherScene}', " +
                        $"which already got its ids. Generating the standalone class '{rule.OutputName}' instead.");
        }
        else if (rule.Flatten && AnvilScriptResolver.DeclaresMember(scriptType, AnimationsClassName))
        {
            // Without Flatten the node classes are renamed on a clash instead (see AppendNodeClasses).
            GD.PushWarning($"Anvil: '{scriptType.Name}' already declares a member named '{AnimationsClassName}', " +
                        $"so ids for scene '{scenePath}' can't be added to it. " +
                        $"Generating the standalone class '{rule.OutputName}' instead (or rename that member).");
        }
        else
        {
            claimedScripts[scriptType] = scenePath;
            GD.Print($"Anvil: Scene '{scenePath}' -> adding ids to script class " +
                    $"'{(scriptType.Namespace is { Length: > 0 } ns ? ns + "." : "")}{scriptType.Name}'.");
            return new Block(scriptType.Namespace ?? "", scriptType.Name, false, rule, info, scriptType);
        }

        if (!AnvilNaming.IsValidOutputName(rule.OutputName))
        {
            GD.PushWarning($"Anvil: Scene '{scenePath}' has no script class to extend, and its output name " +
                        $"'{rule.OutputName}' is empty, reserved, or not a valid C# class name. Skipped.");
            return null;
        }

        if (!takenNames.Add(rule.OutputName))
        {
            GD.PushWarning($"Anvil: Duplicate output name '{rule.OutputName}' (scene '{scenePath}'). " +
                        "Skipped to avoid a naming conflict.");
            return null;
        }

        return new Block("Anvil", rule.OutputName, true, rule, info, null);
    }

    private static void AppendBlock(StringBuilder sb, Block block)
    {
        bool hasNamespace = block.Namespace.Length > 0;
        string indent = hasNamespace ? Indent : "";

        if (hasNamespace)
        {
            sb.AppendLine($"namespace {block.Namespace}");
            sb.AppendLine("{");
        }

        string declaration = block.IsStandalone ? "public static class" : "partial class";

        sb.AppendLine($"{indent}{declaration} {block.ClassName}");
        sb.AppendLine($"{indent}{{");

        AppendAnimations(sb, block, indent + Indent);

        sb.AppendLine($"{indent}}}");

        if (hasNamespace)
            sb.AppendLine("}");

        sb.AppendLine();
    }

    private static string ShortName(string animation)
    {
        int slash = animation.LastIndexOf('/');
        return slash < 0 ? animation : animation[(slash + 1)..];
    }

    private static void AppendAnimations(StringBuilder sb, Block block, string indent)
    {
        bool wantPlayers = block.Rule.Sources.HasFlag(SceneSources.AnimationPlayers);
        bool wantSprites = block.Rule.Sources.HasFlag(SceneSources.AnimatedSprites);

        List<AnvilSceneReader.AnimationNodeInfo> players = wantPlayers ? block.Info.AnimationPlayers : new();
        List<AnvilSceneReader.AnimationNodeInfo> sprites = wantSprites ? block.Info.AnimatedSprites : new();

        List<AnvilSceneReader.AnimationNodeInfo> nodes = [.. players, .. sprites];
        if (nodes.Count == 0)
        {
            GD.PushWarning($"Anvil: Scene '{block.Rule.ResolvePath()}' contains no AnimationPlayer or AnimatedSprite2D/3D.");
            return;
        }

        if (block.Rule.Flatten)
            AppendMergedClass(sb, nodes, indent);
        else
            AppendNodeClasses(sb, block, nodes, indent);
    }

    private static void AppendMergedClass(StringBuilder sb, List<AnvilSceneReader.AnimationNodeInfo> nodes, string indent)
    {
        var merged = new AnvilSceneReader.AnimationNodeInfo(
            AnimationsClassName,
            ".",
            nodes.SelectMany(n => n.Animations)
                 .Distinct()
                 .OrderBy(n => n, StringComparer.Ordinal)
                 .ToList());

        sb.AppendLine($"{indent}public static class {AnimationsClassName}");
        sb.AppendLine($"{indent}{{");

        AppendAnimationMembers(sb, merged, AnimationsClassName, indent + Indent);

        sb.AppendLine($"{indent}}}");
    }

    private static void AppendNodeClasses(
        StringBuilder sb, Block block, List<AnvilSceneReader.AnimationNodeInfo> nodes, string indent)
    {
        var scope = new AnvilNameScope(block.ClassName);

        var duplicatedNames = nodes
            .GroupBy(n => n.NodeName)
            .Where(g => g.Count() > 1)
            .Select(g => g.Key)
            .ToHashSet();

        foreach (var node in nodes)
        {
            string rawNodeName = duplicatedNames.Contains(node.NodeName) ? node.NodePath : node.NodeName;

            if (!scope.TryClaim(rawNodeName, "animation node", out string nodeId))
                continue;

            if (block.ScriptType is not null && Clashes(block.ScriptType, nodeId))
            {
                string original = nodeId;

                do nodeId += NodeClassSuffix;
                while (Clashes(block.ScriptType, nodeId));

                GD.PushWarning($"Anvil: Node '{node.NodeName}' in scene '{block.Rule.ResolvePath()}' would generate a class " +
                               $"named '{original}', which clashes with a Godot class or a member of '{block.ClassName}'. " +
                               $"Generated as '{nodeId}' instead (or rename the node).");
            }

            sb.AppendLine($"{indent}public static class {nodeId}");
            sb.AppendLine($"{indent}{{");

            AppendAnimationMembers(sb, node, nodeId, indent + Indent);

            sb.AppendLine($"{indent}}}");
        }
    }

    private static bool Clashes(Type scriptType, string name)
    {
        return ClassDB.ClassExists(name) || AnvilScriptResolver.DeclaresMember(scriptType, name);
    }

    private static void AppendAnimationMembers(StringBuilder sb, AnvilSceneReader.AnimationNodeInfo node, string className, string indent)
    {
        var memberScope = new AnvilNameScope(className);
        List<string> hintNames = [];

        var shortNameCounts = node.Animations
            .GroupBy(ShortName)
            .ToDictionary(g => g.Key, g => g.Count());

        foreach (string animation in node.Animations)
        {
            string shortName = ShortName(animation);
            string idSource = shortNameCounts[shortName] > 1 ? animation : shortName;

            if (!memberScope.TryClaim(idSource, $"animation '{animation}' in '{className}'", out string id))
                continue;

            if (animation.Contains(','))
            {
                GD.PushWarning($"Anvil: Animation '{animation}' contains a comma and was excluded from HintString " +
                               "(would corrupt the enum hint string).");
            }
            else
            {
                hintNames.Add(animation);
            }

            sb.AppendLine($"{indent}public static readonly StringName {id} = \"{AnvilNaming.EscapeLiteral(animation)}\";");
        }

        AnvilGenerator.AppendHintString(sb, hintNames, indent);
    }
}
