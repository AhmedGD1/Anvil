using Godot;
using System.IO;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System;

namespace Anvil;

public static class AnvilGenerator
{
    private const string Ind1 = "";
    private const string Ind2 = Ind1 + "    ";

    private static readonly HashSet<string> ExcludedExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".import", ".uid"
    };

    public static HashSet<string> GenerateAndSave(AnvilRuleSet rules)
    {
        List<AnvilRule> validRules = AnvilValidator.ValidateRules(rules);

        StringBuilder sb = new();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using Godot;");
        sb.AppendLine();
        sb.AppendLine("namespace Anvil;");
        sb.AppendLine();
        AppendStringNameClass(sb, "GlobalGroups", "global group", GetGlobalGroupNames());
        AppendStringNameClass(sb, "InputActions", "input action", GetInputActionNames());
        AppendStringNameClass(sb, "AudioBuses", "audio bus", GetAudioBusNames());
        AppendPhysicsLayersClass(sb, "PhysicsLayers2D", "layer_names/2d_physics/");
        AppendPhysicsLayersClass(sb, "PhysicsLayers3D", "layer_names/3d_physics/");

        foreach (var rule in validRules)
        {
            AppendFolderClass(sb, rule);
        }

        AnvilFileIO.SaveGeneratedFile("AnvilIds", sb.ToString());

        return validRules.Select(r => r.OutputName).ToHashSet();
    }

    internal static void AppendHintString(StringBuilder sb, List<string> hintNames, string indent = Ind2)
    {
        sb.AppendLine();
        sb.AppendLine($"{indent}public const string {AnvilNaming.HintStringMember} = " +
                      $"\"{AnvilNaming.EscapeLiteral(string.Join(',', hintNames))}\";");
    }

    private static void AppendStringNameClass(StringBuilder sb, string className, string kind, IEnumerable<string> rawNames)
    {
        sb.AppendLine($"{Ind1}public static class {className}");
        sb.AppendLine($"{Ind1}{{");

        var scope = new AnvilNameScope(className);
        List<string> hintNames = [];

        foreach (string rawName in rawNames)
        {
            if (!scope.TryClaim(rawName, kind, out string id))
                continue;

            if (rawName.Contains(','))
            {
                GD.PushWarning($"Anvil: {kind} '{rawName}' contains a comma and was excluded from HintString " +
                               "(would corrupt the enum hint string).");
            }
            else
            {
                hintNames.Add(rawName);
            }

            sb.AppendLine($"{Ind2}public static readonly StringName {id} = \"{AnvilNaming.EscapeLiteral(rawName)}\";");
        }

        AppendHintString(sb, hintNames);

        sb.AppendLine($"{Ind1}}}");
        sb.AppendLine();
    }

    private static IEnumerable<string> GetAudioBusNames()
    {
        int busCount = AudioServer.GetBusCount();
        for (int i = 0; i < busCount; i++)
        {
            string busName = AudioServer.GetBusName(i);
            if (!string.IsNullOrWhiteSpace(busName))
                yield return busName;
        }
    }

    private static IEnumerable<string> GetGlobalGroupNames()
    {
        const string prefix = "global_group/";

        foreach (Godot.Collections.Dictionary property in ProjectSettings.Singleton.GetPropertyList())
        {
            string settingName = property["name"].AsString();
            if (!settingName.StartsWith(prefix))
                continue;

            string groupName = settingName[prefix.Length..];
            if (!string.IsNullOrWhiteSpace(groupName))
                yield return groupName;
        }
    }

    private static IEnumerable<string> GetInputActionNames()
    {
        const string prefix = "input/";

        foreach (Godot.Collections.Dictionary property in ProjectSettings.Singleton.GetPropertyList())
        {
            string settingName = property["name"].AsString();
            if (!settingName.StartsWith(prefix))
                continue;

            string actionName = settingName[prefix.Length..];
            if (string.IsNullOrWhiteSpace(actionName))
                continue;

            if (actionName.StartsWith("ui_"))
                continue;

            yield return actionName;
        }
    }

    private static void AppendPhysicsLayersClass(StringBuilder sb, string className, string settingPrefix)
    {
        sb.AppendLine($"{Ind1}public static class {className}");
        sb.AppendLine($"{Ind1}{{");

        var scope = new AnvilNameScope(className);

        foreach (Godot.Collections.Dictionary property in ProjectSettings.Singleton.GetPropertyList())
        {
            string settingName = property["name"].AsString();
            if (!settingName.StartsWith(settingPrefix))
                continue;

            string suffix = settingName[settingPrefix.Length..];
            if (!suffix.StartsWith("layer_"))
                continue;

            if (!int.TryParse(suffix.AsSpan("layer_".Length), out int layerNumber) || layerNumber is < 1 or > 32)
                continue;

            string layerName = ProjectSettings.Singleton.GetSetting(settingName).AsString();
            if (string.IsNullOrWhiteSpace(layerName))
                continue;

            if (!scope.TryClaim(layerName, "physics layer", out string id))
                continue;

            uint bitValue = 1u << (layerNumber - 1);
            sb.AppendLine($"{Ind2}public const uint {id} = {bitValue};");
        }

        sb.AppendLine($"{Ind1}}}");
        sb.AppendLine();
    }

    private static bool ShouldIncludeFile(string filePath, HashSet<string> includedExtensions)
    {
        string extension = Path.GetExtension(filePath);

        if (ExcludedExtensions.Contains(extension))
            return false;

        return includedExtensions.Count == 0 || includedExtensions.Contains(extension);
    }

    private static void AppendFolderClass(StringBuilder sb, AnvilRule rule)
    {
        sb.AppendLine($"{Ind1}public static class {rule.OutputName}");
        sb.AppendLine($"{Ind1}{{");

        string dirPath = ProjectSettings.GlobalizePath(rule.SourceFolder);
        List<string> hintNames = [];

        var searchOption = rule.Recursive ? SearchOption.AllDirectories : SearchOption.TopDirectoryOnly;
        var includedExtensions = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        if (rule.IncludedExtensions is not null)
        foreach (string configuredExtension in rule.IncludedExtensions)
        {
            if (string.IsNullOrWhiteSpace(configuredExtension))
                continue;

            string extension = configuredExtension.Trim();
            if (!extension.StartsWith(".", StringComparison.Ordinal))
                extension = "." + extension;

            includedExtensions.Add(extension);
        }

        var files = Directory.GetFiles(dirPath, "*", searchOption)
            .Where(f => ShouldIncludeFile(f, includedExtensions))
            .OrderBy(f => f, StringComparer.Ordinal);

        var scope = new AnvilNameScope(rule.OutputName);
        string kind = $"file in '{rule.SourceFolder}'";

        foreach (var file in files)
        {
            string fileName = Path.GetFileNameWithoutExtension(file);

            if (!scope.TryClaim(fileName, kind, out string id))
                continue;

            if (rule.Mode == ForgeMode.FullPath)
            {
                string relativePath = Path.GetRelativePath(dirPath, file).Replace('\\', '/');
                string resPath = $"{rule.SourceFolder.TrimEnd('/')}/{relativePath}";

                sb.AppendLine($"{Ind2}public static readonly StringName {id} = \"{AnvilNaming.EscapeLiteral(resPath)}\";");
            }
            else
            {
                if (fileName.Contains(','))
                {
                    GD.PushWarning($"Anvil: '{fileName}' contains a comma and was excluded from HintString " +
                                   $"(would corrupt the enum hint string).");
                }
                else
                {
                    hintNames.Add(fileName);
                }

                sb.AppendLine($"{Ind2}public static readonly StringName {id} = \"{AnvilNaming.EscapeLiteral(fileName)}\";");
            }
        }

        if (rule.Mode == ForgeMode.Id)
            AppendHintString(sb, hintNames);

        sb.AppendLine($"{Ind1}}}");
        sb.AppendLine();
    }
}
